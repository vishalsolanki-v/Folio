"""Folio logo B (fanned sheets): one geometry -> adaptive foreground, monochrome, SVG master, 512 px PNG."""
import math, os, sys
from PIL import Image, ImageDraw

repo = sys.argv[1]
res = os.path.join(repo, "app/src/main/res")
brand = os.path.join(repo, "docs/brand")
os.makedirs(brand, exist_ok=True)

INK, PAPER, COBALT, GREY, LINE = "#1F1F1E", "#FAF9F5", "#2E5AAC", "#6B6A65", "#C9C6BD"
# Sheets in a 180-unit design space: (x, y, w, h, radius, angle, pivot, colour)
SHEETS = [
    (38, 54, 62, 82, 8, -12, (69, 95), GREY),
    (62, 48, 62, 82, 8, -2, (93, 89), COBALT),
    (84, 46, 62, 82, 8, 9, (115, 87), PAPER),
]
LINES = [(96, 70, 36, 5), (96, 84, 36, 5), (96, 98, 22, 5)]  # on the front sheet, same rotation
SCALE, OFFSET = 0.47, 54 - 90 * 0.47  # 180-space -> 108-dp adaptive canvas, centred; stays inside the 66 dp safe zone


def rrect(x, y, w, h, r):
    return (f"M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} V{y + h - r} A{r},{r} 0 0 1 {x + w - r},{y + h} "
            f"H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} V{y + r} A{r},{r} 0 0 1 {x + r},{y} Z")


def vector(body, comment):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:scaleX="{SCALE}" android:scaleY="{SCALE}" android:translateX="{OFFSET:.2f}" android:translateY="{OFFSET:.2f}">
{body}    </group>
</vector>
'''


def group(angle, pivot, inner):
    return (f'        <group android:rotation="{angle}" android:pivotX="{pivot[0]}" android:pivotY="{pivot[1]}">\n{inner}'
            f'        </group>\n')


# Colour foreground
body = ""
for x, y, w, h, r, a, p, c in SHEETS:
    inner = f'            <path android:fillColor="{c}" android:pathData="{rrect(x, y, w, h, r)}" />\n'
    if c == PAPER:
        for lx, ly, lw, lh in LINES:
            inner += f'            <path android:fillColor="{LINE}" android:pathData="{rrect(lx, ly, lw, lh, lh / 2)}" />\n'
    body += group(a, p, inner)
open(os.path.join(res, "drawable/ic_launcher_foreground.xml"), "w", encoding="utf8").write(
    vector(body, "Folio logo: three fanned sheets (every kind of file in one place). Generated by docs/brand/make_icon.py."))

# Monochrome (Android 13+ themed icons): one tint, depth from alpha, the front sheet's lines cut out
body = ""
for (x, y, w, h, r, a, p, c), alpha in zip(SHEETS, (0.45, 0.7, 1.0)):
    path = rrect(x, y, w, h, r)
    extra = ' android:fillType="evenOdd"' if c == PAPER else ""
    if c == PAPER:
        path += " " + " ".join(rrect(lx, ly, lw, lh, lh / 2) for lx, ly, lw, lh in LINES)
    body += group(a, p, f'            <path android:fillColor="#FFFFFFFF" android:fillAlpha="{alpha}"{extra} android:pathData="{path}" />\n')
open(os.path.join(res, "drawable/ic_launcher_monochrome.xml"), "w", encoding="utf8").write(
    vector(body, "Folio logo, single colour for themed icons. Generated by docs/brand/make_icon.py."))

# SVG master (108 x 108, full-bleed ink square; launchers and stores apply their own mask)
svg = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="1080" height="1080">',
       f'<rect width="108" height="108" fill="{INK}"/>', f'<g transform="translate({OFFSET:.2f} {OFFSET:.2f}) scale({SCALE})">']
for x, y, w, h, r, a, p, c in SHEETS:
    svg.append(f'<g transform="rotate({a} {p[0]} {p[1]})"><rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{c}"/>')
    if c == PAPER:
        svg += [f'<rect x="{lx}" y="{ly}" width="{lw}" height="{lh}" rx="{lh / 2}" fill="{LINE}"/>' for lx, ly, lw, lh in LINES]
    svg.append("</g>")
svg.append("</g></svg>")
open(os.path.join(brand, "folio-logo.svg"), "w", encoding="utf8").write("\n".join(svg) + "\n")

# 512 px PNG (drawn at 4x, then downscaled for smooth edges)
def render(size, circle=False):
    k = size * 4 / 108
    img = Image.new("RGBA", (size * 4, size * 4), INK)
    for x, y, w, h, r, a, p, c in SHEETS:
        layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
        d = ImageDraw.Draw(layer)
        t = lambda u, v: ((OFFSET + u * SCALE) * k, (OFFSET + v * SCALE) * k)
        d.rounded_rectangle([t(x, y), t(x + w, y + h)], radius=r * SCALE * k, fill=c)
        if c == PAPER:
            for lx, ly, lw, lh in LINES:
                d.rounded_rectangle([t(lx, ly), t(lx + lw, ly + lh)], radius=lh / 2 * SCALE * k, fill=LINE)
        img.alpha_composite(layer.rotate(-a, resample=Image.BICUBIC, center=t(*p)))
    if circle:
        mask = Image.new("L", img.size, 0)
        ImageDraw.Draw(mask).ellipse([0, 0, img.size[0] - 1, img.size[1] - 1], fill=255)
        img.putalpha(mask)
    return img.resize((size, size), Image.LANCZOS)

render(512).save(os.path.join(brand, "folio-icon-512.png"))
render(512, circle=True).save(os.path.join(brand, "folio-icon-512-round.png"))
print("done")
